#!/usr/bin/env python3
"""
Merge several docs pages into one long page.

    python3 tools/merge_section.py docs/get-started.md \
        docs/overview.md docs/getting-started.md docs/architecture.md \
        --section=Features docs/features/index.md

What it does
  1. Moves each source page into a hidden folder (docs/.fragments/<page>/) so MkDocs
     stops building it as its own page. Nothing is deleted.
  2. Joins them into one page. Each source page's H1 becomes an H2, and every
     heading below it drops one level, so the table of contents lists everything.
  3. Rewrites links that pointed at the old pages, across every other page in
     docs/, so nothing 404s.

Run it again after editing a fragment, or after adding a page to the list.
"""
import re
import sys
import shutil
from pathlib import Path

DOCS = Path("docs")


def slug(text: str) -> str:
    """Same anchor MkDocs generates for a heading."""
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"[:!]?[a-z][a-z0-9_-]*:", "", text)  # drop :material-icon:
    text = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"\s+", "-", text)


def split_front_matter(text: str):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    return (m.group(1), text[m.end():]) if m else ("", text)


def downshift(text: str) -> str:
    """Drop every heading one level, ignoring fenced code."""
    out, fence = [], None
    for line in text.splitlines():
        s = line.lstrip()
        if s.startswith("```") or s.startswith("~~~"):
            marker = s[:3]
            fence = None if fence == marker else (fence or marker)
            out.append(line)
            continue
        if fence is None and re.match(r"^#{1,6} ", line):
            line = "#" + line
        out.append(line)
    return "\n".join(out)


def main(argv):
    if len(argv) < 3:
        sys.exit("usage: merge_section.py <output.md> [--section=TITLE] <source.md> ...")

    out_path = Path(argv[1])
    fragment_dir = DOCS / ".fragments" / out_path.stem
    items = []
    sources = []
    for argument in argv[2:]:
        if argument.startswith("--section="):
            title = argument.partition("=")[2].strip()
            if not title:
                sys.exit("section titles cannot be empty")
            items.append(("section", title))
            continue

        source = Path(argument)
        # Already merged once? Then sources live in the fragment folder.
        source = source if source.exists() else fragment_dir / source.name
        sources.append(source)
        items.append(("source", source))

    missing = [str(p) for p in sources if not p.exists()]
    if missing:
        sys.exit("stopped, these are not there: " + ", ".join(missing))
    fragment_dir.mkdir(parents=True, exist_ok=True)

    redirect, pieces = {}, []
    for kind, value in items:
        if kind == "section":
            pieces.append(f"## {value}")
            continue

        src = value
        _meta, body = split_front_matter(src.read_text())
        first = re.search(r"^#+(.+)$", body, re.M)
        title = first.group(1).strip() if first else src.stem
        redirect[src.name] = (out_path.name, slug(title))

        body = body.strip("\n")
        if re.search(r"^# ", body, re.M):
            body = downshift(body)
            # the page title keeps its icon in the nav, but the heading on the
            # long page drops it so the anchor is simply #architecture
            body = re.sub(
                r"(?m)^(## )[^\n]*?:material-[a-z0-9-]+:\s*",
                r"\1",
                body,
                count=1,
            )
        else:
            body = "## " + title + "\n\n" + body
        pieces.append(body)

        dest = fragment_dir / src.name
        if src.resolve() != dest.resolve():
            if dest.exists():
                dest.unlink()
            shutil.move(str(src), str(dest))

    MARK = "<!-- generated by tools/merge_section.py: {} -->"
    # This file is generated entirely from sources, so never append its prior output.
    existing = ""
    if re.search(r"^# ", existing, re.M):
        head = existing.rstrip("\n") + "\n\n" + "\n\n".join(pieces) + "\n"
    else:
        head = "# " + out_path.stem.replace("-", " ").title() + "\n\n" + "\n\n".join(pieces) + "\n"
    out_path.write_text(MARK.format(" ".join(p.name for p in sources)) + "\n" + head)

    changed = []
    for page in DOCS.rglob("*.md"):
        if ".fragments" in page.parts:
            continue
        self_page = page == out_path
        text = original = page.read_text()
        if self_page:
            text = re.sub(
                r"\]\((?:\.\.?/|[A-Za-z0-9_.-]+/)*" + re.escape(out_path.name) + r"(#[^)]*)?\)",
                lambda m: f"]({m.group(1) or '#'})",
                text,
            )
        for old_name, (new_name, anchor) in redirect.items():
            target = f"#{anchor}" if self_page else f"{new_name}#{anchor}"
            pre = r"(?:\.\.?/|[A-Za-z0-9_.-]+/)*"  # tolerate links through folders
            if self_page:
                # a link to another page that is now on this one becomes an anchor
                text = re.sub(r"\]\(" + pre + r"{}(#[^)]*)?\)".format(re.escape(old_name)),
                              lambda m: f"]({m.group(1)})" if m.group(1) else f"]({target})", text)
            else:
                text = text.replace(f"({old_name}#", f"({new_name}#")
                text = re.sub(r"\]\(" + pre + r"{}\)".format(re.escape(old_name)),
                              f"]({new_name}#{anchor})", text)
        if text != original:
            page.write_text(text)
            changed.append(str(page))

    print(f"Wrote {out_path}  ({len(head.splitlines())} lines)")
    for old_name, (new_name, anchor) in redirect.items():
        print(f"  {old_name} -> {new_name}#{anchor}   (kept in {fragment_dir}/{old_name})")
    if changed:
        print("Rewrote links in:")
        for c in changed:
            print("  " + c)


if __name__ == "__main__":
    main(sys.argv)
